package com.navercorp.cubridqa.builder.exec;

/**
 * Generates the bash scripts that execution_mode=vm runs on a QA VM.
 *
 * The case runner reproduces, step for step, what CTP shell does around each case
 * (CTP/shell/src/com/navercorp/cubridqa/shell/main/Test.java), but without CTP's
 * Java dispatcher: resetProcess (Constants.createLinKillScripts, local variant),
 * resetCUBRID_linux, runTestCase_linux (with addSshInfoScript), doFinalCheck
 * (do_check_more_errors from the VM's own CTP) and collectGeneralResult. Keeping
 * the same steps is what lets a case behave as it does in QAHome regression.
 */
public final class VmScriptFactory {

    /** Marker lines the executor uses to split the runner output into phases. */
    public static final String PHASE_PREFIX = "===== [builder-tester vm] ";
    public static final String CASE_EXIT_PREFIX = PHASE_PREFIX + "case exit code: ";

    private VmScriptFactory() {}

    /**
     * Installs a Builder-Tester package into cubridHome the way CTP's run_cubrid_install
     * installs a tarball (InstallBuildByPackage + cpCCIDriver), then takes the
     * ~/.CUBRID_SHELL_FM snapshot that CTP's deploy step (DeployOneNode.backup_linux)
     * takes after every install and that resetCUBRID restores from before each case.
     */
    public static String createInstallScript(String cubridHome, String ctpHome, String packagePath, String markerContent) {
        StringBuilder s = new StringBuilder();
        s.append("#!/bin/bash\n");
        s.append("# Generated by Builder-Tester (execution_mode=vm): install a build like CTP's run_cubrid_install.\n");
        appendBaseEnv(s, cubridHome, ctpHome);
        appendResetProcessesFunction(s);
        s.append("PKG=").append(quote(packagePath)).append("\n\n");

        s.append("echo \"").append(PHASE_PREFIX).append("stop processes\"\n");
        s.append("bt_reset_processes >/dev/null 2>&1\n\n");

        s.append("echo \"").append(PHASE_PREFIX).append("install $PKG into $CUBRID\"\n");
        s.append("mkdir -p \"$CUBRID\" || exit 1\n");
        s.append("rm -rf \"$CUBRID\"/* \"$CUBRID\"/.builder_tester_build\n");
        s.append("cd \"$CUBRID\" || exit 1\n");
        s.append("if tar -tzf \"$PKG\" 2>/dev/null | grep -m1 -q '^_install/CUBRID/'; then\n");
        s.append("  tar -xzf \"$PKG\" --strip-components=2 _install/CUBRID || { echo \"[ERROR] extraction failed\"; exit 1; }\n");
        s.append("else\n");
        s.append("  tar -xzf \"$PKG\" || { echo \"[ERROR] extraction failed\"; exit 1; }\n");
        s.append("  if [ -d ./CUBRID ]; then mv ./CUBRID/* . && rm -rf ./CUBRID; fi\n");
        s.append("fi\n");
        s.append("[ -x \"$CUBRID/bin/cubrid_rel\" ] || { echo \"[ERROR] cubrid_rel not found after extraction\"; exit 1; }\n");
        s.append("mkdir -p \"$CUBRID/databases\"\n\n");

        s.append("# cpCCIDriver (run_cubrid_install)\n");
        s.append("for h in $(find \"$CUBRID/cci\" -name '*.h' 2>/dev/null); do\n");
        s.append("  mkdir -p \"$CUBRID/include\"; rm -rf \"$CUBRID/include/$(basename \"$h\")\"; cp -rf \"$h\" \"$CUBRID/include/\"\n");
        s.append("done\n");
        s.append("for l in $(find \"$CUBRID/cci\" -name 'libcascci*' 2>/dev/null); do\n");
        s.append("  rm -rf \"$CUBRID/lib/$(basename \"$l\")\"; cp -rf \"$l\" \"$CUBRID/lib/\"\n");
        s.append("done\n\n");

        s.append("cubrid_rel || { echo \"[ERROR] installed build does not run\"; exit 1; }\n\n");

        s.append("echo \"").append(PHASE_PREFIX).append("snapshot ~/.CUBRID_SHELL_FM\"\n");
        s.append("rm -rf ~/.CUBRID_SHELL_FM > /dev/null 2>&1\n");
        s.append("cp -r \"$CUBRID\" ~/.CUBRID_SHELL_FM || exit 1\n");
        s.append("printf '%s\\n' ").append(quote(markerContent)).append(" > \"$CUBRID/.builder_tester_build\"\n");
        s.append("echo \"").append(PHASE_PREFIX).append("install done\"\n");
        return s.toString();
    }

    /**
     * Runs one case. caseDir is the case's ".../cases" directory and caseFile its script name.
     */
    public static String createCaseScript(String cubridHome, String ctpHome, String caseDir, String caseFile,
                                          String sshPort, String bigSpaceDir, String defaultDbcharset,
                                          String ignoreCoreByKeywords, String pgidFile) {
        String resultFile = (caseFile.endsWith(".sh") ? caseFile.substring(0, caseFile.length() - 3) : caseFile) + ".result";
        StringBuilder s = new StringBuilder();
        s.append("#!/bin/bash\n");
        s.append("# Generated by Builder-Tester (execution_mode=vm): one CTP shell case, CTP's per-case steps.\n");
        s.append("echo $$ > ").append(quote(pgidFile)).append("\n");
        appendBaseEnv(s, cubridHome, ctpHome);
        appendResetProcessesFunction(s);
        s.append("CASE_DIR=").append(quote(caseDir)).append("\n");
        s.append("CASE_FILE=").append(quote(caseFile)).append("\n");
        s.append("RESULT_FILE=").append(quote(resultFile)).append("\n");
        s.append("BUILD_ID=$(cubrid_rel 2>/dev/null | grep CUBRID | awk -F ')' '{print $1}' | awk -F '(' '{print $NF}')\n\n");

        s.append("ssh_info() {\n");
        s.append("  export TEST_SSH_HOST=`hostname -i`\n");
        s.append("  export TEST_SSH_PORT=").append(quote(sshPort)).append("\n");
        s.append("  export TEST_SSH_USER=`echo $USER`\n");
        s.append("  export TEST_BUIILD_ID=\"$BUILD_ID\"\n");
        s.append("}\n\n");

        s.append("echo \"").append(PHASE_PREFIX).append("reset processes\"\n");
        s.append("bt_reset_processes\n\n");

        s.append("echo \"").append(PHASE_PREFIX).append("reset CUBRID\"\n");
        s.append("(\n");
        s.append("  rm -rf ${CUBRID}/conf/*\n");
        s.append("  cp -rf ~/.CUBRID_SHELL_FM/conf/* ${CUBRID}/conf/\n");
        s.append("  rm -rf ${CUBRID}/databases/*\n");
        s.append("  cp -rf ~/.CUBRID_SHELL_FM/databases/* ${CUBRID}/databases/\n");
        s.append("  rm -rf ${CUBRID}/lib/libcubrid_??_??.so\n");
        s.append("  rm -rf ${CUBRID}/lib/libcubrid_all_locales.so\n");
        s.append("  rm -rf ${CUBRID}/var/* >/dev/null 2>&1\n");
        s.append("  find ${CUBRID}/log -type f -print | xargs -i rm -rf {} \n");
        s.append("  find ${CUBRID}/ -name \"core.[0-9][0-9]*\" | xargs -i rm -rf {} \n");
        s.append("  find ${CUBRID}/ -name \"core\" | xargs -i rm -rf {} \n");
        s.append("  find \"$CASE_DIR\" -name \"core.[0-9][0-9]*\" | xargs -i rm -rf {} \n");
        s.append("  find \"$CASE_DIR\" -name \"core\" | xargs -i rm -rf {} \n");
        s.append(") 2>&1\n\n");

        s.append("echo \"").append(PHASE_PREFIX).append("run case $CASE_DIR/$CASE_FILE (build $BUILD_ID)\"\n");
        s.append("(\n");
        s.append("  cd \"$CASE_DIR\" || exit 2\n");
        s.append("  ulimit -c unlimited\n");
        // runTestCase_linux: JAVA_HOME_<context version> wins when the VM defines it; the version
        // is CommonUtils' "64bits", and Builder-Tester builds are 64-bit
        s.append("  if [ \"$JAVA_HOME_64BITS\" ]; then\n");
        s.append("    export JAVA_HOME=$JAVA_HOME_64BITS\n");
        s.append("  fi\n");
        s.append("  export TEST_BIG_SPACE=$(echo $TEST_BIG_SPACE)\n");
        s.append("  export TEST_BIG_SPACE=`if [ \"$TEST_BIG_SPACE\" = '' ]; then echo ").append(quote(bigSpaceDir))
            .append(" ; else echo $TEST_BIG_SPACE; fi`\n");
        s.append("  if [ \"$TEST_BIG_SPACE\" != '' ]; then mkdir -p $TEST_BIG_SPACE; rm -rf $TEST_BIG_SPACE/*; fi\n");
        if (defaultDbcharset != null && !defaultDbcharset.trim().isEmpty()) {
            s.append("  export CUBRID_CHARSET=").append(quote(defaultDbcharset.trim())).append("\n");
        }
        appendExcludedCores(s, ignoreCoreByKeywords, "  ");
        s.append("  echo > \"$RESULT_FILE\"\n");
        s.append("  ssh_info\n");
        appendResultFileBeforeInit(s, "  ");
        s.append("  sh \"$CASE_FILE\" 2>&1\n");
        s.append(")\n");
        s.append("CASE_EXIT=$?\n");
        s.append("rm -f \"$CASE_DIR/").append(RESULT_FILE_BEFORE_INIT).append("\"\n");
        s.append("echo \"").append(CASE_EXIT_PREFIX).append("$CASE_EXIT\"\n\n");

        s.append("echo \"").append(PHASE_PREFIX).append("final check (do_check_more_errors)\"\n");
        s.append("(\n");
        s.append("  cd\n");
        s.append("  source /dev/stdin <<EOF\n");
        s.append("`grep -E \"SKIP_CHECK_FATAL_ERROR\" \"$CASE_DIR/$CASE_FILE\" `\n");
        s.append("EOF\n");
        appendExcludedCores(s, ignoreCoreByKeywords, "  ");
        s.append("  ssh_info\n");
        s.append("  source $init_path/shell_utils.sh && do_check_more_errors \"$CASE_DIR\"\n");
        s.append(") 2>&1\n\n");

        s.append("echo \"").append(PHASE_PREFIX).append("result file\"\n");
        s.append("cat \"$CASE_DIR/$RESULT_FILE\" 2>/dev/null\n");
        s.append("exit 0\n");
        return s.toString();
    }

    /**
     * Collects a readable snapshot of what the case left behind (small text files of the
     * case dir plus $CUBRID/log) into one text file, and a tarball of the same files.
     */
    public static String createArtifactScript(String cubridHome, String caseDir, String textOut, String tarOut) {
        StringBuilder s = new StringBuilder();
        s.append("#!/bin/bash\n");
        s.append("CASE_DIR=").append(quote(caseDir)).append("\n");
        s.append("CUBRID=").append(quote(cubridHome)).append("\n");
        s.append("TEXT_OUT=").append(quote(textOut)).append("\n");
        s.append("TAR_OUT=").append(quote(tarOut)).append("\n");
        s.append("LIST=$(mktemp)\n");
        s.append("trap 'rm -f \"$LIST\"' EXIT\n");
        s.append("( cd \"$CASE_DIR\" && find . -type f -size -10M | sort ) > \"$LIST\"\n");
        s.append("{\n");
        s.append("  echo \"# Files left in $CASE_DIR after the run (ls -la)\"\n");
        s.append("  ls -la \"$CASE_DIR\"\n");
        s.append("  budget=2097152\n");
        s.append("  while IFS= read -r f; do\n");
        s.append("    p=\"$CASE_DIR/${f#./}\"\n");
        s.append("    grep -Iq . \"$p\" 2>/dev/null || continue\n");
        s.append("    [ $budget -le 0 ] && { echo; echo \"# (output budget reached; see $TAR_OUT)\"; break; }\n");
        s.append("    echo; echo \"===== ${f#./} =====\"\n");
        s.append("    head -c 262144 \"$p\"\n");
        s.append("    budget=$((budget - $(stat -c %s \"$p\")))\n");
        s.append("  done < \"$LIST\"\n");
        s.append("  for f in $(find \"$CUBRID/log\" -type f -size -10M 2>/dev/null | sort); do\n");
        s.append("    grep -Iq . \"$f\" 2>/dev/null || continue\n");
        s.append("    echo; echo \"===== \\$CUBRID/log/${f#$CUBRID/log/} =====\"\n");
        s.append("    tail -c 262144 \"$f\"\n");
        s.append("  done\n");
        s.append("} > \"$TEXT_OUT\" 2>&1\n");
        s.append("( cd \"$CASE_DIR\" && tar -czf \"$TAR_OUT\" -T \"$LIST\" ) 2>/dev/null\n");
        s.append("exit 0\n");
        return s.toString();
    }

    /** Stops whatever the case left running; the same reset CTP does before each case and at close. */
    public static String createResetScript(String cubridHome, String ctpHome) {
        StringBuilder s = new StringBuilder();
        s.append("#!/bin/bash\n");
        appendBaseEnv(s, cubridHome, ctpHome);
        appendResetProcessesFunction(s);
        s.append("bt_reset_processes >/dev/null 2>&1\n");
        s.append("exit 0\n");
        return s.toString();
    }

    private static void appendBaseEnv(StringBuilder s, String cubridHome, String ctpHome) {
        s.append("if [ -f \"$HOME/.cubrid.sh\" ]; then . \"$HOME/.cubrid.sh\" >/dev/null 2>&1; fi\n");
        s.append("export CUBRID=").append(quote(cubridHome)).append("\n");
        s.append("export CUBRID_DATABASES=$CUBRID/databases\n");
        s.append("export PATH=$CUBRID/bin:$PATH\n");
        s.append("export LD_LIBRARY_PATH=$CUBRID/lib:$CUBRID/cci/lib:$LD_LIBRARY_PATH\n");
        s.append("export CTP_HOME=").append(quote(ctpHome)).append("\n");
        s.append("export init_path=${CTP_HOME}/shell/init_path\n");
        s.append("export PATH=${CTP_HOME}/bin:${CTP_HOME}/common/script:$PATH\n");
        s.append("ulimit -c unlimited\n\n");
    }

    /**
     * CTP's Constants.createLinKillScripts(inLocal=true). Java processes whose command line
     * contains com.navercorp.cubridqa are spared, which includes this Tester.
     */
    private static void appendResetProcessesFunction(StringBuilder s) {
        s.append("bt_kill() { eval \"$1\" | xargs -i kill -9 {} ; kill -9 `eval \"$1\"` 2>/dev/null; }\n");
        s.append("bt_reset_processes() {\n");
        s.append("  cubrid service stop\n");
        String[] patterns = {"cub_admin", "cub_master", "cub_auto", "cub_broker", "cub_server", "cub", "broker",
            "cm_admin", "csql", "loadjava", "make_locale", "migrate", "shard"};
        for (String p : patterns) {
            s.append("  bt_kill \"ps -u $USER -o pid,comm| grep -v grep | grep ").append(p).append(" | awk '{print \\$1}'\"\n");
        }
        s.append("  ipcs | grep $USER | awk '{print $2}'  | xargs -i ipcrm -m {}\n");
        s.append("  ctp_java_pid_list=`ps -u $USER -o pid,command| grep -v grep | grep -E 'com.navercorp.cubridqa|service.Server' | awk '{print $1}'`\n");
        s.append("  all_java_pid_list=`ps -u $USER -o pid,comm| grep -v grep | grep -i java | awk '{print $1}'`\n");
        s.append("  final_list=\"\"\n");
        s.append("  for x in ${all_java_pid_list};do isExistPid=`echo ${ctp_java_pid_list}|grep -w $x|wc -l`;if [ $isExistPid -eq 0 ];then final_list=\"${final_list} $x\" ;fi;done\n");
        s.append("  bt_kill \"echo ${final_list}\"\n");
        s.append("  bt_kill \"ps -u $USER -o pid,comm| grep -v grep | grep -i sleep | awk '{print \\$1}'\"\n");
        s.append("  bt_kill \"ps -u $USER -o pid,comm| grep -v grep | grep -i expect | awk '{print \\$1}'\"\n");
        s.append("  bt_kill \"ps -u $USER -o pid,comm| grep -v grep | grep -i dos2unix | awk '{print \\$1}'\"\n");
        s.append("}\n\n");
    }

    /** Where CTP init's write before it names the result file goes (see appendResultFileBeforeInit). */
    static final String RESULT_FILE_BEFORE_INIT = ".result_before_init";

    /**
     * CTP's init writes its "test start" line to ${cur_path}/$result_file before it sets
     * result_file (init.sh, need_count_time), so every case logged "init.sh: line 708: .../cases/:
     * Is a directory". That one write gets a scratch file; init names the real result file right
     * after. Not the case's own .result: the case's helper scripts would inherit the name and write
     * into it, which in regression (result_file unset) they cannot.
     */
    static void appendResultFileBeforeInit(StringBuilder s, String indent) {
        s.append(indent).append("export result_file=").append(RESULT_FILE_BEFORE_INIT).append("\n");
    }

    private static void appendExcludedCores(StringBuilder s, String ignoreCoreByKeywords, String indent) {
        if (ignoreCoreByKeywords != null && !ignoreCoreByKeywords.trim().isEmpty()) {
            s.append(indent).append("export EXCLUDED_CORES_BY_ASSERT_LINE=").append(quote(ignoreCoreByKeywords.trim())).append("\n");
        }
    }

    /** Single-quotes a value for bash. */
    static String quote(String value) {
        if (value == null) {
            return "''";
        }
        return "'" + value.replace("'", "'\"'\"'") + "'";
    }
}
